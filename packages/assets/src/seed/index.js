import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { applySeedFiles } from './apply.js';
import { importBalance } from './importers/balance.js';
import { importCities } from './importers/cities.js';
import { importConfig } from './importers/config.js';
import { importCrafting } from './importers/crafting.js';
import { importFaction } from './importers/faction.js';
import { importMaps } from './importers/maps.js';
import { importNpcs } from './importers/npcs.js';
import { importObjects } from './importers/objects.js';
import { importSpells } from './importers/spells.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PACKAGE_ROOT = path.resolve(__dirname, '../..');

const DEFAULTS = {
  datsDir: path.join(PACKAGE_ROOT, 'public/dats'),
  mapsMetaDir: path.join(PACKAGE_ROOT, 'public/maps'),
  outputDir: path.join(PACKAGE_ROOT, 'seeds'),
};

const IMPORTERS = [
  { key: 'objects', file: '01_objects.sql', run: importObjects },
  { key: 'spells', file: '02_spells.sql', run: importSpells },
  { key: 'npcs', file: '03_npcs.sql', run: importNpcs },
  { key: 'maps', file: '04_maps.sql', run: importMaps },
  { key: 'cities', file: '05_cities.sql', run: importCities },
  { key: 'balance', file: '06_balance.sql', run: importBalance },
  { key: 'crafting', file: '07_crafting.sql', run: importCrafting },
  { key: 'faction', file: '08_faction.sql', run: importFaction },
  { key: 'config', file: '09_config.sql', run: importConfig },
];

const parseOnly = (only) => {
  if (!only) {
    return null;
  }

  return new Set(
    only
      .split(',')
      .map((value) => value.trim().toLowerCase())
      .filter(Boolean),
  );
};

const writeSqlFile = (outputDir, fileName, statements) => {
  const filePath = path.join(outputDir, fileName);
  const header = `-- Generated by bao seed\n-- ${new Date().toISOString()}\n\n`;
  fs.writeFileSync(filePath, `${header}${statements.join('\n')}\n`, 'utf8');
};

export const runSeed = async (options = {}) => {
  const datsDir = path.resolve(options.datsDir ?? DEFAULTS.datsDir);
  const mapsMetaDir = path.resolve(options.mapsMetaDir ?? DEFAULTS.mapsMetaDir);
  const outputDir = path.resolve(options.outputDir ?? DEFAULTS.outputDir);
  const only = parseOnly(options.only);
  const dryRun = Boolean(options.dryRun);
  const debug = Boolean(options.debug);
  const apply = Boolean(options.apply);

  if (!dryRun && !fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  const summary = [];

  for (const importer of IMPORTERS) {
    if (only && !only.has(importer.key)) {
      continue;
    }

    const context = {
      datsDir,
      mapsMetaDir,
      debug,
    };

    const result = importer.run(context);
    summary.push({
      type: importer.key,
      count: result.count,
      skipped: result.skipped,
      statements: result.statements.length,
    });

    if (debug) {
      console.log(
        `[seed] ${importer.key}: ${result.skipped ? 'skipped' : `${result.count} records, ${result.statements.length} statements`}`,
      );
    }

    if (!dryRun) {
      const filePath = path.join(outputDir, importer.file);
      if (result.skipped || result.statements.length === 0) {
        if (fs.existsSync(filePath)) {
          fs.unlinkSync(filePath);
        }
      } else {
        writeSqlFile(outputDir, importer.file, result.statements);
      }
    }
  }

  if (apply) {
    if (dryRun) {
      console.log('[seed] --dry-run: skipping database apply');
    } else {
      const applied = await applySeedFiles({ outputDir, debug });
      summary.push({ type: 'apply', count: applied, skipped: false, statements: applied });
    }
  }

  return summary;
};
