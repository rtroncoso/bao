import assert from 'node:assert/strict';
import { parseSeedStatements, splitSqlStatements } from './sqlStatements.js';

const npcInsert =
  "INSERT INTO `npcs` (`id`, `description`) VALUES (34, 'Hola;\ncomerciante') ON DUPLICATE KEY UPDATE `description`=VALUES(`description`)";
const shopInsert =
  'INSERT INTO `npc_shop_items` (`npcId`, `slot`, `objectId`, `amount`) VALUES (34, 1, 100, 1) ON DUPLICATE KEY UPDATE `objectId`=VALUES(`objectId`)';

const sql = `-- Generated by bao seed
-- 2026-06-12T00:00:00.000Z

-- @bao-npc:34
${npcInsert};
${shopInsert};
`;

const statements = splitSqlStatements(normalizeForTest(sql));
assert.equal(statements.length, 3, statements);

const parsed = parseSeedStatements(sql);
assert.equal(parsed.length, 2);
assert.equal(parsed[0].npcId, 34);
assert.equal(parsed[1].npcId, 34);
assert.equal(parsed[0].npcBlockEnd, false);
assert.equal(parsed[1].npcBlockEnd, true);

console.log('sqlStatements tests passed');

function normalizeForTest(seedSql) {
  return seedSql
    .replace(/^-- Generated by bao seed\r?\n-- [^\n]+\r?\n+/u, '')
    .replace(/^(-- @bao-npc:\d+)\r?\n/gm, ';\n$1;\n');
}
