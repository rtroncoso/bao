const isStatementSeparator = (sql, index) =>
  sql[index] === ';' && /^;\s*\n/.test(sql.slice(index));

export const splitSqlStatements = (sql) => {
  const statements = [];
  let current = '';
  let inString = false;

  for (let index = 0; index < sql.length; index += 1) {
    const char = sql[index];

    if (inString) {
      current += char;

      if (char === "'") {
        if (sql[index + 1] === "'") {
          current += "'";
          index += 1;
        } else {
          inString = false;
        }
      }

      continue;
    }

    if (char === "'") {
      inString = true;
      current += char;
      continue;
    }

    if (isStatementSeparator(sql, index)) {
      const trimmed = current.trim();
      if (trimmed.length > 0) {
        statements.push(trimmed);
      }

      current = '';
      index += 1;
      while (index < sql.length && sql[index] !== '\n') {
        index += 1;
      }
      continue;
    }

    current += char;
  }

  const trimmed = current.trim();
  if (trimmed.length > 0) {
    statements.push(trimmed);
  }

  return statements;
};

const NPC_MARKER_RE = /^-- @bao-npc:(\d+)$/;

const normalizeSeedSql = (sql) =>
  sql
    .replace(/^-- Generated by bao seed\r?\n-- [^\n]+\r?\n+/u, '')
    .replace(/^(-- @bao-npc:\d+)\r?\n/gm, ';\n$1;\n');

export const parseSeedStatements = (sql) => {
  const statements = [];
  let currentNpcId = null;

  for (const chunk of splitSqlStatements(normalizeSeedSql(sql))) {
    const npcMarker = chunk.match(NPC_MARKER_RE);
    if (npcMarker) {
      if (statements.length > 0) {
        statements[statements.length - 1].npcBlockEnd = true;
      }
      currentNpcId = Number.parseInt(npcMarker[1], 10);
      continue;
    }

    if (chunk.startsWith('--')) {
      continue;
    }

    statements.push({
      sql: chunk,
      npcId: currentNpcId,
      npcBlockEnd: false,
    });
  }

  if (statements.length > 0) {
    statements[statements.length - 1].npcBlockEnd = true;
  }

  return statements;
};
